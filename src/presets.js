export function loadPreset(key) {
  const p = PRESETS[key];
  if (!p) throw new Error(`알 수 없는 프리셋: ${key}`);
  const m = createMolecule();
  for (const [el, pos] of p.atoms) addAtom(m, el, pos);
  for (const [i, j, order] of p.bonds) addBond(m, i, j, order ?? 1);
  return m;
}
